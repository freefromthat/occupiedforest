  let lang = 'en';
  try {
    const stored = localStorage.getItem('fo.lang');
    if (stored === 'de' || stored === 'en') lang = stored;
    else if ((navigator.language || '').toLowerCase().startsWith('de')) lang = 'de';
  } catch (e) { /* ignore */ }

  function format(str, vars) {
    if (!vars) return str;
    return String(str).replace(/\{(\w+)\}/g, function (m, key) {
      return vars[key] !== undefined && vars[key] !== null ? String(vars[key]) : m;
    });
  }

  function t(key, vars) {
    const table = dict[lang] || dict.en;
    let val = table[key];
    if (val === undefined) val = dict.en[key];
    if (val === undefined) val = key;
    return format(val, vars);
  }

  function L(obj) {
    if (obj === null || obj === undefined) return '';
    if (typeof obj === 'string') return obj;
    return obj[lang] !== undefined ? obj[lang] : (obj.en !== undefined ? obj.en : '');
  }

  function applyStatic(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      const key = el.getAttribute('data-i18n');
      el.textContent = t(key);
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
  }

  function setLang(next) {
    if (next !== 'en' && next !== 'de') return;
    lang = next;
    try { localStorage.setItem('fo.lang', next); } catch (e) { /* ignore */ }
    document.documentElement.lang = next;
    applyStatic(document);
    document.querySelectorAll('.lang-btn').forEach(function (b) {
      b.classList.toggle('active', b.getAttribute('data-lang') === next);
    });
    document.dispatchEvent(new CustomEvent('fo:lang', { detail: { lang: next } }));
  }

  document.documentElement.lang = lang;

  window.FO = window.FO || {};
  FO.i18n = {
    t: t,
    L: L,
    setLang: setLang,
    applyStatic: applyStatic,
    getLang: function () { return lang; },
    dict: dict
  };
